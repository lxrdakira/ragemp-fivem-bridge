/**
 * Collection names are stored inside CPedVariationInfo in the generated YMT.
 * Different clothing builders use either the short DLC name or the full
 * ped-prefixed name, so discover the mounted name instead of assuming one.
 */
function getMountedCollectionName(ped: number, requestedName: string): string | null {
  const model = GetEntityModel(ped) >>> 0;
  const cacheKey = `${model}:${requestedName}`;
  const cached = resolvedCollectionNames.get(cacheKey);
  if (cached) return cached;

  const count = GetPedCollectionsCount(ped);
  for (let index = 0; index < count; index++) {
    const mountedName = GetPedCollectionName(ped, index);
    if (
      mountedName === requestedName ||
      mountedName.endsWith(`_${requestedName}`)
    ) {
      resolvedCollectionNames.set(cacheKey, mountedName);
      if (CLOTHING_DIAGNOSTICS_ENABLED) console.log(`[clothing-bridge] mounted collection ${requestedName} -> ${mountedName}`);
      return mountedName;
    }
  }

  if (!missingCollectionWarnings.has(cacheKey)) {
    missingCollectionWarnings.add(cacheKey);
    console.warn(
      `[clothing-bridge] collection ${requestedName} is not mounted for model ${model}; collections=${count}`,
    );
  }
  return null;
}

