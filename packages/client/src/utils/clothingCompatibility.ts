export type CollectionDrawable = {
  collection: string;
  drawable: number;
};

export function resolveLegacyCollectionDrawable(
  mapping: LegacyMapping | undefined,
  drawable: number,
): CollectionDrawable | null {
  if (!mapping || drawable < mapping.base) return null;
  let local = drawable - mapping.base;
  for (const range of mapping.ranges) {
    if (local < range.count) return { collection: range.collection, drawable: local };
    local -= range.count;
  }
  return null;
}

type PedClothingMappings = {
  components: Readonly<Record<number, LegacyMapping>>;
  props: Readonly<Record<number, LegacyMapping>>;
};

function getPedClothingMappings(ped: number): PedClothingMappings | null {
  if (!ped) return null;
  const model = GetEntityModel(ped) >>> 0;
  if (model === MALE_FREEMODE_MODEL) {
    return { components: MALE_COMPONENTS, props: MALE_PROPS };
  }
  if (model === FEMALE_FREEMODE_MODEL) {
    return { components: FEMALE_COMPONENTS, props: FEMALE_PROPS };
  }
  return null;
}

function safeTexture(texture: number, maxTextures: number): number {
  const value = texture | 0;
  if (value < 0 || (maxTextures > 0 && value >= maxTextures)) return 0;
  return value;
}

/**
 * The variation metadata can be mounted before its streamed drawable is ready.
 * Ask the game to preload the exact collection item and reapply it once the
 * preload completes. The sequence guard prevents a delayed /tsc request from
 * overwriting a newer clothing selection.
 */
function preloadAndReapplyCollectionComponent(
  ped: number,
  component: number,
  collection: string,
  drawable: number,
  texture: number,
  palette: number,
  token: number,
): void {
  const pendingKey = `${ped}:${component}`;
  try {
    SetPedCollectionPreloadVariationData(ped, component, collection, drawable, texture);
  } catch (error) {
    console.warn(
      `[clothing-bridge] preload request failed component=${component} collection=${collection} local=${drawable}: ${String(error)}`,
    );
    return;
  }

  let attempts = 0;
  const poll = () => {
    if (pendingComponentPreloads.get(pendingKey) !== token || !DoesEntityExist(ped)) return;
    attempts++;

    let finished = false;
    try {
      finished = HasPedPreloadVariationDataFinished(ped);
    } catch (error) {
      console.warn(`[clothing-bridge] preload status failed: ${String(error)}`);
      return;
    }

    if (!finished && attempts < 30) {
      setTimeout(poll, 100);
      return;
    }

    if (finished) {
      SetPedCollectionComponentVariation(
        ped,
        component,
        collection,
        drawable,
        texture,
        palette,
      );
    }

    if (CLOTHING_DIAGNOSTICS_ENABLED) {
      const actualCollection = GetPedDrawableVariationCollectionName(ped, component);
      const actualLocal = GetPedDrawableVariationCollectionLocalIndex(ped, component);
      console.log(
      `[clothing-bridge] preload component=${component} collection=${collection} local=${drawable} finished=${finished} attempts=${attempts} actualCollection=${actualCollection} actualLocal=${actualLocal}`,
      );
    } else if (!finished) {
      console.warn(`[clothing-bridge] preload timed out component=${component} collection=${collection} local=${drawable}`);
    }
    if (pendingComponentPreloads.get(pendingKey) === token) {
      pendingComponentPreloads.delete(pendingKey);
    }
  };
  setTimeout(poll, 0);
}

export function setCompatibleComponentVariation(
  ped: number,
  componentId: number,
  drawableId: number,
  textureId: number,
  paletteId = 0,
): boolean {
  const component = componentId | 0;
  const drawable = Math.max(0, drawableId | 0);
  const preloadKey = `${ped}:${component}`;
  const preloadToken = ++componentPreloadSequence;
  pendingComponentPreloads.set(preloadKey, preloadToken);

  const mappings = getPedClothingMappings(ped);
  if (mappings) {
    const resolved = resolveLegacyCollectionDrawable(mappings.components[component], drawable);
    if (resolved) {
      const collection = getMountedCollectionName(ped, resolved.collection);
      if (!collection) return false;
      const maxDrawables = GetNumberOfPedCollectionDrawableVariations(ped, component, collection);
      if (maxDrawables <= resolved.drawable) {
        console.warn(
          `[clothing-bridge] invalid component collection=${collection} component=${component} local=${resolved.drawable} count=${maxDrawables}`,
        );
        return false;
      }

      // Address add-on clothes by collection first. This is the only stable
      // way to bind a drawable to the YMT that owns it; global indexes can
      // change whenever another clothing resource is added or reordered.
      const globalDrawable = GetPedDrawableGlobalIndexFromCollection(
        ped,
        component,
        collection,
        resolved.drawable,
      );
      if (globalDrawable < 0) {
        console.warn(
          `[clothing-bridge] cannot convert component collection=${collection} component=${component} local=${resolved.drawable}`,
        );
        return false;
      }
      const maxTextures = GetNumberOfPedCollectionTextureVariations(
        ped,
        component,
        collection,
        resolved.drawable,
      );
      const texture = safeTexture(textureId, maxTextures);
      const palette = Math.max(0, paletteId | 0);
      const valid = IsPedCollectionComponentVariationValid(
        ped,
        component,
        collection,
        resolved.drawable,
        texture,
      );
      preloadAndReapplyCollectionComponent(
        ped,
        component,
        collection,
        resolved.drawable,
        texture,
        palette,
        preloadToken,
      );
      SetPedCollectionComponentVariation(
        ped,
        component,
        collection,
        resolved.drawable,
        texture,
        palette,
      );

      // Some older BestMP builds have an incomplete collection setter. Keep
      // the global conversion as a verified fallback, never as the primary
      // path. A successful collection call reports the same global drawable.
      let actualGlobal = GetPedDrawableVariation(ped, component);
      let setter = "collection";
      if (actualGlobal !== globalDrawable) {
        SetPedComponentVariation(ped, component, globalDrawable, texture, palette);
        actualGlobal = GetPedDrawableVariation(ped, component);
        setter = "global-fallback";
      }

      const logKey = `component:${component}:${collection}:${resolved.drawable}:${texture}`;
      if (CLOTHING_DIAGNOSTICS_ENABLED && !appliedVariationLogs.has(logKey)) {
        const actualCollection = GetPedDrawableVariationCollectionName(ped, component);
        const actualLocal = GetPedDrawableVariationCollectionLocalIndex(ped, component);
        appliedVariationLogs.add(logKey);
        console.log(
          `[clothing-bridge] applied component=${component} legacy=${drawable} collection=${collection} local=${resolved.drawable} texture=${texture}/${maxTextures} global=${globalDrawable} actual=${actualGlobal} actualCollection=${actualCollection} actualLocal=${actualLocal} valid=${valid} setter=${setter} count=${maxDrawables}`,
        );
        setTimeout(() => {
          console.log(
            `[clothing-bridge] retained component=${component} expected=${globalDrawable} actual=${GetPedDrawableVariation(ped, component)}`,
          );
        }, 500);
      }
      return true;
    }
  }

  pendingComponentPreloads.delete(preloadKey);

  const maxDrawables = GetNumberOfPedDrawableVariations(ped, component);
  if (maxDrawables <= drawable) return false;
  const maxTextures = GetNumberOfPedTextureVariations(ped, component, drawable);
  SetPedComponentVariation(
    ped,
    component,
    drawable,
    safeTexture(textureId, maxTextures),
    Math.max(0, paletteId | 0),
  );
  return true;
}

export function setCompatiblePropIndex(
  ped: number,
  propId: number,
  drawableId: number,
  textureId: number,
  attach = true,
): boolean {
  const prop = propId | 0;
  const drawable = drawableId | 0;
  if (drawable < 0) {
    ClearPedProp(ped, prop);
    return true;
  }

  const mappings = getPedClothingMappings(ped);
  if (mappings) {
    const resolved = resolveLegacyCollectionDrawable(mappings.props[prop], drawable);
    if (resolved) {
      const collection = getMountedCollectionName(ped, resolved.collection);
      if (!collection) return false;
      const maxDrawables = GetNumberOfPedCollectionPropDrawableVariations(ped, prop, collection);
      if (maxDrawables <= resolved.drawable) {
        console.warn(
          `[clothing-bridge] invalid prop collection=${collection} prop=${prop} local=${resolved.drawable} count=${maxDrawables}`,
        );
        return false;
      }
      const globalDrawable = GetPedPropGlobalIndexFromCollection(
        ped,
        prop,
        collection,
        resolved.drawable,
      );
      if (globalDrawable < 0) {
        console.warn(
          `[clothing-bridge] cannot convert prop collection=${collection} prop=${prop} local=${resolved.drawable}`,
        );
        return false;
      }
      const maxTextures = GetNumberOfPedCollectionPropTextureVariations(
        ped,
        prop,
        collection,
        resolved.drawable,
      );
      const texture = safeTexture(textureId, maxTextures);
      SetPedCollectionPropIndex(ped, prop, collection, resolved.drawable, texture, !!attach);

      let actualGlobal = GetPedPropIndex(ped, prop);
      let setter = "collection";
      if (actualGlobal !== globalDrawable) {
        SetPedPropIndex(ped, prop, globalDrawable, texture, !!attach);
        actualGlobal = GetPedPropIndex(ped, prop);
        setter = "global-fallback";
      }

      const logKey = `prop:${prop}:${collection}:${resolved.drawable}:${texture}`;
      if (CLOTHING_DIAGNOSTICS_ENABLED && !appliedVariationLogs.has(logKey)) {
        appliedVariationLogs.add(logKey);
        console.log(
          `[clothing-bridge] applied prop=${prop} legacy=${drawable} collection=${collection} local=${resolved.drawable} texture=${texture}/${maxTextures} global=${globalDrawable} actual=${actualGlobal} setter=${setter} count=${maxDrawables}`,
        );
      }
      return true;
    }
  }

  const maxDrawables = GetNumberOfPedPropDrawableVariations(ped, prop);
  if (maxDrawables <= drawable) return false;
  const maxTextures = GetNumberOfPedPropTextureVariations(ped, prop, drawable);
  SetPedPropIndex(ped, prop, drawable, safeTexture(textureId, maxTextures), !!attach);
  return true;
}
